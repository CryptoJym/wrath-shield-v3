/**
 * Get patterns that match an event for enhanced classification
 */
export function findPatternsForEvent(event: {
  type: string;
  domain?: string;
  source: string;
  timestamp: Date;
  payload?: unknown;
}): PatternMatch[] {
  const patternRecognizer = getPatternRecognizer();
  return patternRecognizer.findMatchingPatterns({
    id: `temp_${Date.now()}`,
    type: event.type as 'message' | 'task' | 'notification' | 'escalation',
    domain: event.domain,
    source: event.source,
    timestamp: event.timestamp,
    payload: event.payload,
    priority: 'normal',
  });
}

/**
 * Migrate existing preference model rules to the lifecycle tracking system.
 *
 * This is a one-time operation that imports all existing urgency triggers
 * and auto-archive patterns into the RuleLifecycleManager for provenance
 * tracking, decay management, and contradiction detection.
 *
 * Call this when:
 * - First setting up provenance tracking on an existing system
 * - After loading preferences that might have rules not in the lifecycle system
 */
export async function migrateRulesToLifecycleSystem(): Promise<{
  imported: number;
  skipped: number;
  errors: string[];
}> {
  const preferences = await loadPreferences();
  const lifecycleManager = getRuleLifecycleManager();
  const errors: string[] = [];
  let imported = 0;
  let skipped = 0;

  console.log('[SemanticBridge] Starting migration of preference rules to lifecycle system...');

  // Import urgency triggers
  for (const rule of preferences.urgency_triggers) {
    try {
      await lifecycleManager.addRule(rule, 'urgency_trigger', []);
      imported++;
    } catch (error) {
      // Skip if already exists (duplicate key error)
      if (error instanceof Error && error.message.includes('UNIQUE constraint')) {
        skipped++;
      } else {
        errors.push(`Urgency trigger "${rule.pattern}": ${error}`);
      }
    }
  }

  // Import auto-archive patterns
  for (const rule of preferences.auto_archive_patterns) {
    try {
      await lifecycleManager.addRule(rule, 'auto_archive', []);
      imported++;
    } catch (error) {
      // Skip if already exists
      if (error instanceof Error && error.message.includes('UNIQUE constraint')) {
        skipped++;
      } else {
        errors.push(`Auto-archive pattern "${rule.pattern}": ${error}`);
      }
    }
  }

  console.log(
    `[SemanticBridge] Migration complete: ${imported} imported, ${skipped} skipped (already exists), ${errors.length} errors`
  );

  return { imported, skipped, errors };
}

/**
 * Sync lifecycle system state back to preference model.
 *
 * This ensures the preference model only contains active rules from
 * the lifecycle system, removing any that have been archived or
 * decayed below threshold.
 *
 * Call this after running decay cycles or resolving contradictions.
 */
export async function syncLifecycleToPreferences(): Promise<{
  urgencyTriggers: number;
  autoArchivePatterns: number;
  removed: number;
}> {
  const preferences = await loadPreferences();
  const lifecycleManager = getRuleLifecycleManager();
  const activeRules = await lifecycleManager.getActiveRules();

  const originalUrgencyCount = preferences.urgency_triggers.length;
  const originalArchiveCount = preferences.auto_archive_patterns.length;

  // Build lookup of active rules by pattern
  const activeUrgencyPatterns = new Set(
    activeRules
      .filter((r) => r.category === 'urgency_trigger')
      .map((r) => r.rule.pattern.toLowerCase())
  );

  const activeArchivePatterns = new Set(
    activeRules
      .filter((r) => r.category === 'auto_archive')
      .map((r) => r.rule.pattern.toLowerCase())
  );

  // Filter preference model to only active rules
  preferences.urgency_triggers = preferences.urgency_triggers.filter((rule) =>
    activeUrgencyPatterns.has(rule.pattern.toLowerCase())
  );

  preferences.auto_archive_patterns = preferences.auto_archive_patterns.filter((rule) =>
    activeArchivePatterns.has(rule.pattern.toLowerCase())
  );

  const removed =
    originalUrgencyCount -
    preferences.urgency_triggers.length +
    originalArchiveCount -
    preferences.auto_archive_patterns.length;

  if (removed > 0) {
    await savePreferences(preferences);
    console.log(
      `[SemanticBridge] Synced preferences: removed ${removed} inactive rules`
    );
  }

  return {
    urgencyTriggers: preferences.urgency_triggers.length,
    autoArchivePatterns: preferences.auto_archive_patterns.length,
    removed,
  };
}
