/**
 * Semantic Learning Bridge
 *
 * Connects the Pattern Recognizer, Preference Model, and Decision Queue
 * to enable cross-system learning and adaptive behavior improvement.
 *
 * This module serves as the "feedback loop" for the Cognitive Synthesis Engine:
 *
 * 1. Pattern Detection → Preference Rules
 *    When PatternRecognizer detects recurring patterns, convert them to
 *    preference model rules (urgency triggers, auto-archive patterns)
 *
 * 2. Decision Resolution → Correction Learning
 *    When a decision is resolved, feed it back to the Preference Model
 *    as a learning signal (similar to recordCorrection)
 *
 * 3. Preference Insights → Pattern Guidance
 *    Use preference model knowledge to guide pattern detection
 *
 * SECURITY: This module must ONLY be imported in server-side code.
 */

