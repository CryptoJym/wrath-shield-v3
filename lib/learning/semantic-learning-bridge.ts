/**
 * Learn from a resolved decision
 *
 * When a human resolves a NEEDS_DECISION item, we can learn:
 * - Which option they chose (and why)
 * - Whether the LLM's recommendation was correct
 * - Patterns in the decision context
 */
async function learnFromDecisionResolution(
  decision: PendingDecision,
  preferences: JamesPreferenceModel
): Promise<LearningInsight | null> {
  if (decision.status !== 'resolved' || !decision.selectedOptionId) {
    return null;
  }

  const selectedOption = decision.options.find((o) => o.id === decision.selectedOptionId);
  const recommendedOption = decision.options.find((o) => o.recommended);

  if (!selectedOption) {
    return null;
  }

  // If user chose the recommended option, this validates the LLM's reasoning
  // If not, this is a learning opportunity

  const wasRecommendedChosen = recommendedOption?.id === selectedOption.id;

  if (wasRecommendedChosen) {
    // Reinforce the LLM's decision-making - could boost pattern confidence
    console.log(`[SemanticBridge] Decision ${decision.id}: User confirmed LLM recommendation`);

    return {
      id: `insight_${Date.now()}`,
      type: 'decision_to_correction',
      source: 'decision_queue',
      target: 'preference_model',
      description: `User confirmed recommended option "${selectedOption.label}" - positive reinforcement`,
      timestamp: new Date().toISOString(),
      applied: true,
      metadata: {
        decisionId: decision.id,
        optionChosen: selectedOption.label,
        wasRecommended: true,
        domain: decision.domain,
      },
    };
  }

  // User chose a different option - this is a correction
  console.log(
    `[SemanticBridge] Decision ${decision.id}: User chose "${selectedOption.label}" over recommended "${recommendedOption?.label}"`
  );

  // Record this as a correction in the preference model
  try {
    await recordCorrection(
      decision.id,
      {
        urgency: mapPriorityToUrgency(decision.priority),
        domain: (decision.domain as Domain) || 'general',
        action: recommendedOption?.action || 'unknown',
      },
      {
        urgency: inferUrgencyFromOption(selectedOption),
        domain: (decision.domain as Domain) || 'general',
        action: selectedOption.action,
      },
      decision.userFeedback || `User chose "${selectedOption.label}" instead of recommended option`,
      {
        type: 'notification',
        summary: decision.title,
        content: decision.context,
      }
    );

    return {
      id: `insight_${Date.now()}`,
      type: 'decision_to_correction',
      source: 'decision_queue',
      target: 'preference_model',
      description: `Recorded correction: "${selectedOption.label}" chosen over "${recommendedOption?.label}"`,
      timestamp: new Date().toISOString(),
      applied: true,
      metadata: {
        decisionId: decision.id,
        optionChosen: selectedOption.label,
        recommendedOption: recommendedOption?.label,
        reason: decision.userFeedback,
        domain: decision.domain,
      },
    };
  } catch (error) {
    console.error('[SemanticBridge] Error recording correction:', error);
    return null;
  }
}

/**
 * Map decision priority to urgency level
 */
function mapPriorityToUrgency(priority: 'critical' | 'high' | 'medium' | 'low'): UrgencyLevel {
  switch (priority) {
    case 'critical':
      return 'critical';
    case 'high':
      return 'high';
    case 'medium':
      return 'medium';
    case 'low':
      return 'low';
    default:
      return 'medium';
  }
}

/**
 * Infer urgency level from the chosen option
 */
function inferUrgencyFromOption(option: DecisionOption): UrgencyLevel {
  const actionLower = option.action.toLowerCase();

  if (actionLower.includes('escalate') || actionLower.includes('urgent')) {
    return 'critical';
  }
  if (actionLower.includes('high') || actionLower.includes('priorit')) {
    return 'high';
  }
  if (actionLower.includes('archive') || actionLower.includes('dismiss')) {
    return 'background';
  }
  if (actionLower.includes('defer') || actionLower.includes('later')) {
    return 'low';
  }

  return 'medium';
}

