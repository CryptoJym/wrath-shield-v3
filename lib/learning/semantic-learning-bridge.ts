/**
 * Semantic Learning Bridge
 *
 * Orchestrates cross-system learning between Pattern Recognizer,
 * Preference Model, and Decision Queue.
 */
export class SemanticLearningBridge {
  private config: SemanticLearningConfig;
  private insights: LearningInsight[] = [];
  private lastLearningCycle: number = 0;

  constructor(config?: Partial<SemanticLearningConfig>) {
    this.config = { ...DEFAULT_CONFIG, ...config };
    console.log('[SemanticBridge] Initialized with config:', this.config);
  }

  /**
   * Run a learning cycle
   *
   * This is the main entry point that should be called periodically
   * (e.g., every 30 minutes or after significant activity).
   */
  async runLearningCycle(): Promise<LearningInsight[]> {
    const startTime = Date.now();
    const cycleInsights: LearningInsight[] = [];

    console.log('[SemanticBridge] Starting learning cycle...');

    try {
      // 1. Load current preferences
      const preferences = await loadPreferences();

      // 2. Process detected patterns
      if (this.config.autoCreateRules) {
        const patternInsights = await this.processPatterns(preferences);
        cycleInsights.push(...patternInsights);
      }

      // 3. Process resolved decisions
      if (this.config.learnFromDecisions) {
        const decisionInsights = await this.processResolvedDecisions(preferences);
        cycleInsights.push(...decisionInsights);
      }

      // 4. Process contradiction detection
      if (this.config.detectContradictions) {
        const contradictionInsights = await this.processContradictions(preferences);
        cycleInsights.push(...contradictionInsights);
      }

      // 5. Process confidence decay for stale rules
      if (this.config.enableDecay) {
        const decayInsights = await this.processDecay(preferences);
        cycleInsights.push(...decayInsights);
      }

      // 6. Save updated preferences if any insights were applied
      const appliedCount = cycleInsights.filter((i) => i.applied).length;
      if (appliedCount > 0) {
        await savePreferences(preferences);
        console.log(`[SemanticBridge] Saved preferences with ${appliedCount} updates`);
      }

      // 7. Track insights
      this.insights.push(...cycleInsights);
      this.lastLearningCycle = Date.now();

      // 8. Publish learning cycle complete event
      if (cycleInsights.length > 0) {
        const eventBus = getEventBus();
        await eventBus.publish(
          createNotificationEvent(
            'semantic-learning-bridge',
            {
              type: 'learning-cycle-complete',
              insightsGenerated: cycleInsights.length,
              insightsApplied: appliedCount,
              durationMs: Date.now() - startTime,
            },
            DOMAINS.LEARNING,
            'low'
          )
        );
      }

      console.log(
        `[SemanticBridge] Learning cycle complete: ${cycleInsights.length} insights (${Date.now() - startTime}ms)`
      );

      return cycleInsights;
    } catch (error) {
      console.error('[SemanticBridge] Learning cycle failed:', error);
      return [];
    }
  }

  /**
   * Process detected patterns and convert to preference rules
   */
  private async processPatterns(preferences: JamesPreferenceModel): Promise<LearningInsight[]> {
    const insights: LearningInsight[] = [];
    const patternRecognizer = getPatternRecognizer();
    const patterns = patternRecognizer.getAllPatterns();

    let rulesCreated = 0;

    for (const pattern of patterns) {
      // Skip if we've created enough rules this cycle
      if (rulesCreated >= this.config.maxRulesPerCycle) {
        break;
      }

      // Check if pattern meets thresholds
      if (
        pattern.confidence < this.config.patternToRuleThreshold ||
        pattern.frequency < this.config.minPatternFrequency
      ) {
        continue;
      }

      // Determine what kind of rule this should be
      const category = categorizePattern(pattern);
      if (category === 'skip') {
        continue;
      }

      // Convert pattern to rule
      const rule = patternToPreferenceRule(pattern);
      if (!rule) {
        continue;
      }

      // Check if similar rule already exists
      const targetList =
        category === 'urgency' ? preferences.urgency_triggers : preferences.auto_archive_patterns;

      const alreadyExists = targetList.some(
        (existing) =>
          existing.pattern.toLowerCase().includes(rule.pattern.toLowerCase()) ||
          rule.pattern.toLowerCase().includes(existing.pattern.toLowerCase())
      );

      if (alreadyExists) {
        continue;
      }

      // Add the new rule to preference model
      targetList.push(rule);
      rulesCreated++;

      // Register rule with RuleLifecycleManager for provenance tracking
      let ruleId: string | undefined;
      try {
        const lifecycleManager = getRuleLifecycleManager();
        const ruleCategory: RuleCategory = category === 'urgency' ? 'urgency_trigger' : 'auto_archive';

        // Extract event IDs from pattern metadata if available
        const derivedFromEvents: string[] = [];
        const patternMetadata = pattern.metadata as Record<string, unknown> | undefined;
        if (patternMetadata?.lastMatchedEventId) {
          derivedFromEvents.push(String(patternMetadata.lastMatchedEventId));
        }
        if (patternMetadata?.sourceEventIds && Array.isArray(patternMetadata.sourceEventIds)) {
          derivedFromEvents.push(...patternMetadata.sourceEventIds.map(String));
        }

        ruleId = await lifecycleManager.addRule(rule, ruleCategory, derivedFromEvents);
        console.log(`[SemanticBridge] Registered rule ${ruleId} in provenance system`);
      } catch (error) {
        console.error('[SemanticBridge] Failed to register rule with lifecycle manager:', error);
      }

      insights.push({
        id: `insight_pattern_${pattern.id}`,
        type: 'pattern_to_rule',
        source: 'pattern_recognizer',
        target: 'preference_model',
        description: `Created ${category} rule from pattern: "${rule.pattern}"`,
        timestamp: new Date().toISOString(),
        applied: true,
        metadata: {
          patternId: pattern.id,
          patternType: pattern.type,
          confidence: pattern.confidence,
          frequency: pattern.frequency,
          ruleCategory: category,
          ruleId, // Include provenance ID for tracking
        },
      });

      console.log(`[SemanticBridge] Created ${category} rule: "${rule.pattern}"`);
    }

    return insights;
  }

  /**
   * Process resolved decisions and learn from them
   */
  private async processResolvedDecisions(
    preferences: JamesPreferenceModel
  ): Promise<LearningInsight[]> {
    const insights: LearningInsight[] = [];
    const decisionQueue = getDecisionQueue();

    // Get recently resolved decisions (last 24 hours)
    const allDecisions = await decisionQueue.getPendingDecisions({ status: 'resolved' });

    const recentCutoff = Date.now() - 24 * 60 * 60 * 1000;
    const recentDecisions = allDecisions.filter(
      (d) => d.resolvedAt && new Date(d.resolvedAt).getTime() > recentCutoff
    );

    for (const decision of recentDecisions) {
      const insight = await learnFromDecisionResolution(decision, preferences);
      if (insight) {
        insights.push(insight);
      }
    }

    return insights;
  }

  /**
   * Process contradiction detection between rules
   *
   * Finds conflicting preference rules and either auto-resolves them
   * or creates insights for human review.
   *
   * Note: The RuleLifecycleManager maintains its own provenance database,
   * so contradiction detection works on tracked rules, not the raw preference arrays.
   */
  private async processContradictions(
    _preferences: JamesPreferenceModel
  ): Promise<LearningInsight[]> {
    const insights: LearningInsight[] = [];

    try {
      const lifecycleManager = getRuleLifecycleManager();

      // Detect contradictions across all tracked rules
      const contradictions = await lifecycleManager.detectContradictions();

      for (const contradiction of contradictions) {
        // Create insight for detected contradiction
        insights.push({
          id: `insight_contradiction_${contradiction.id}`,
          type: 'contradiction_detected',
          source: 'rule_lifecycle',
          target: 'preference_model',
          description: `Contradiction detected: Rule "${contradiction.rule1Id}" conflicts with "${contradiction.rule2Id}" - ${contradiction.description}`,
          timestamp: new Date().toISOString(),
          applied: false,
          metadata: {
            contradictionId: contradiction.id,
            type: contradiction.contradictionType,
            severity: contradiction.severity,
            rule1Id: contradiction.rule1Id,
            rule2Id: contradiction.rule2Id,
            suggestedResolution: contradiction.suggestedResolution,
          },
        });

        // Auto-resolve low severity contradictions
        if (this.config.autoResolveContradictions && contradiction.severity === 'low') {
          // Use suggested resolution or default to merge for low severity
          const resolution = contradiction.suggestedResolution === 'human_review'
            ? 'merge' as const
            : contradiction.suggestedResolution === 'keep_rule1'
              ? 'keep_rule1' as const
              : contradiction.suggestedResolution === 'keep_rule2'
                ? 'keep_rule2' as const
                : 'merge' as const;

          await lifecycleManager.resolveContradiction(contradiction.id, resolution);

          insights.push({
            id: `insight_contradiction_resolved_${contradiction.id}`,
            type: 'contradiction_resolved',
            source: 'rule_lifecycle',
            target: 'preference_model',
            description: `Auto-resolved low-severity contradiction: ${resolution}`,
            timestamp: new Date().toISOString(),
            applied: true,
            metadata: {
              contradictionId: contradiction.id,
              resolution,
              automatic: true,
            },
          });
        }
      }

      if (contradictions.length > 0) {
        console.log(
          `[SemanticBridge] Found ${contradictions.length} contradictions, auto-resolved ${
            insights.filter((i) => i.type === 'contradiction_resolved').length
          }`
        );
      }
    } catch (error) {
      console.error('[SemanticBridge] Error processing contradictions:', error);
    }

    return insights;
  }

  /**
   * Process confidence decay for stale rules
   *
   * Rules that haven't been reinforced recently lose confidence weight.
   * This ensures that old patterns don't dominate over newer behavior.
   *
   * The RuleLifecycleManager handles decay through its own provenance tracking.
   * This method runs the decay cycle and creates insights based on results.
   */
  private async processDecay(
    _preferences: JamesPreferenceModel
  ): Promise<LearningInsight[]> {
    const insights: LearningInsight[] = [];

    try {
      const lifecycleManager = getRuleLifecycleManager();

      // Run the decay cycle - this checks all tracked rules
      const decayResult = await lifecycleManager.runDecayCycle();

      // Create insights for decayed rules
      for (const ruleId of decayResult.decayed) {
        insights.push({
          id: `insight_decay_${Date.now()}_${ruleId}`,
          type: 'rule_decayed',
          source: 'rule_lifecycle',
          target: 'preference_model',
          description: `Rule ${ruleId} had confidence reduced due to lack of reinforcement`,
          timestamp: new Date().toISOString(),
          applied: true,
          metadata: {
            ruleId,
            action: 'decayed',
          },
        });
      }

      // Create insights for archived rules (decayed below threshold)
      for (const ruleId of decayResult.archived) {
        insights.push({
          id: `insight_archived_${Date.now()}_${ruleId}`,
          type: 'rule_decayed',
          source: 'rule_lifecycle',
          target: 'preference_model',
          description: `Rule ${ruleId} was archived after decaying below minimum confidence threshold`,
          timestamp: new Date().toISOString(),
          applied: true,
          metadata: {
            ruleId,
            action: 'archived',
          },
        });
      }

      if (decayResult.decayed.length > 0 || decayResult.archived.length > 0) {
        console.log(
          `[SemanticBridge] Decay cycle: ${decayResult.decayed.length} decayed, ${decayResult.archived.length} archived`
        );
      }
    } catch (error) {
      console.error('[SemanticBridge] Error processing decay:', error);
    }

    return insights;
  }

  /**
   * Reinforce a rule when it matches user behavior
   *
   * Call this when a rule successfully predicts user action.
   * @param ruleId - The rule ID from the provenance system
   * @param eventIds - Optional event IDs that triggered this reinforcement
   */
  async reinforceRule(ruleId: string, eventIds: string[] = []): Promise<void> {
    try {
      const lifecycleManager = getRuleLifecycleManager();
      await lifecycleManager.reinforceRule(ruleId, eventIds);

      console.log(`[SemanticBridge] Reinforced rule: ${ruleId}`);
    } catch (error) {
      console.error('[SemanticBridge] Error reinforcing rule:', error);
    }
  }

  /**
   * Get learning statistics
   */
  getStats(): {
    totalInsights: number;
    appliedInsights: number;
    lastLearningCycle: number | null;
    insightsByType: Record<string, number>;
    insightsBySource: Record<string, number>;
  } {
    const byType: Record<string, number> = {};
    const bySource: Record<string, number> = {};

    for (const insight of this.insights) {
      byType[insight.type] = (byType[insight.type] || 0) + 1;
      bySource[insight.source] = (bySource[insight.source] || 0) + 1;
    }

    return {
      totalInsights: this.insights.length,
      appliedInsights: this.insights.filter((i) => i.applied).length,
      lastLearningCycle: this.lastLearningCycle || null,
      insightsByType: byType,
      insightsBySource: bySource,
    };
  }

  /**
   * Get recent insights
   */
  getRecentInsights(limit: number = 20): LearningInsight[] {
    return this.insights.slice(-limit);
  }

  /**
   * Clear insight history
   */
  clearInsights(): void {
    this.insights = [];
    console.log('[SemanticBridge] Cleared insight history');
  }
}

