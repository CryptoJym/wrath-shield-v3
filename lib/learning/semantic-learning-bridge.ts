/**
 * Learning insight generated by the bridge
 */
export interface LearningInsight {
  id: string;
  type: 'pattern_to_rule' | 'decision_to_correction' | 'preference_update' | 'contradiction_detected' | 'contradiction_resolved' | 'rule_decayed' | 'rule_reinforced';
  source: 'pattern_recognizer' | 'decision_queue' | 'preference_model' | 'rule_lifecycle';
  target: 'preference_model' | 'pattern_recognizer' | 'synthesis_loop' | 'rule_lifecycle';
  description: string;
  timestamp: string;
  applied: boolean;
  metadata?: Record<string, unknown>;
}

/**
 * Bridge configuration
 */
export interface SemanticLearningConfig {
  // Minimum pattern confidence to convert to preference rule
  patternToRuleThreshold: number;

  // Minimum pattern frequency (per week) to consider for rule conversion
  minPatternFrequency: number;

  // Enable automatic rule creation from patterns
  autoCreateRules: boolean;

  // Enable decision resolution learning
  learnFromDecisions: boolean;

  // Maximum rules to create per learning cycle
  maxRulesPerCycle: number;

  // Enable contradiction detection during learning cycles
  detectContradictions: boolean;

  // Auto-resolve low-severity contradictions
  autoResolveContradictions: boolean;

  // Enable confidence decay for stale rules
  enableDecay: boolean;

  // Days without reinforcement before decay starts
  decayGracePeriodDays: number;
}

const DEFAULT_CONFIG: SemanticLearningConfig = {
  patternToRuleThreshold: 0.7,
  minPatternFrequency: 3,
  autoCreateRules: true,
  learnFromDecisions: true,
  maxRulesPerCycle: 5,
  detectContradictions: true,
  autoResolveContradictions: true,
  enableDecay: true,
  decayGracePeriodDays: 30,
};

// ============================================================================
// Pattern to Preference Rule Conversion
// ============================================================================

/**
 * Convert a detected pattern into a preference model rule
 */
function patternToPreferenceRule(pattern: RecurringPattern): PatternRule | null {
  // Skip patterns with low confidence
  if (pattern.confidence < 0.5) {
    return null;
  }

  // Extract keywords from pattern description and examples
  const keywords = extractKeywordsFromPattern(pattern);
  if (keywords.length === 0) {
    return null;
  }

  const rule: PatternRule = {
    pattern: keywords.join('|'),
    isRegex: true,
    caseSensitive: false,
    weight: Math.min(0.9, pattern.confidence),
    learnedAt: new Date().toISOString(),
    source: 'inferred',
    exampleMatches: pattern.examples.slice(0, 3),
  };

  return rule;
}

/**
 * Extract meaningful keywords from a pattern
 */
function extractKeywordsFromPattern(pattern: RecurringPattern): string[] {
  const keywords: string[] = [];

  // Extract from description
  const descWords = pattern.description
    .toLowerCase()
    .replace(/[^\w\s]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length > 4);

  keywords.push(...descWords.slice(0, 3));

  // Extract from examples
  for (const example of pattern.examples) {
    try {
      const parsed = JSON.parse(example);
      if (typeof parsed === 'object') {
        // Extract from subject, title, or content fields
        const text = [parsed.subject, parsed.title, parsed.content]
          .filter(Boolean)
          .join(' ')
          .toLowerCase();

        const words = text
          .replace(/[^\w\s]/g, ' ')
          .split(/\s+/)
          .filter((w) => w.length > 4);

        keywords.push(...words.slice(0, 2));
      }
    } catch {
      // Not JSON, extract directly
      const words = example
        .toLowerCase()
        .replace(/[^\w\s]/g, ' ')
        .split(/\s+/)
        .filter((w) => w.length > 4);

      keywords.push(...words.slice(0, 2));
    }
  }

  // Deduplicate and limit
  return Array.from(new Set(keywords)).slice(0, 5);
}

/**
 * Determine if a pattern should become an urgency trigger or archive pattern
 */
function categorizePattern(pattern: RecurringPattern): 'urgency' | 'archive' | 'skip' {
  const descLower = pattern.description.toLowerCase();

  // Check if this is about escalation or high-priority items
  if (
    descLower.includes('escalat') ||
    descLower.includes('critical') ||
    descLower.includes('urgent') ||
    descLower.includes('high') ||
    pattern.type === 'escalation'
  ) {
    return 'urgency';
  }

  // Check if this is about low-priority or dismissable items
  if (
    descLower.includes('archive') ||
    descLower.includes('dismiss') ||
    descLower.includes('low') ||
    descLower.includes('newsletter') ||
    descLower.includes('promotional')
  ) {
    return 'archive';
  }

  // Default: skip patterns that don't clearly fit
  return 'skip';
}

